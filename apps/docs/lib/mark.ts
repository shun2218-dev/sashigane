/**
 * ブランドのマーク。**さしがねを2枚、180° 向かい合わせた形である。**
 *
 * ## なぜ2枚か
 *
 * 1枚だと**文字の `L` と見分けがつかない。** 向かい合わせると回転対称になり、
 * 文字には見えなくなる。
 *
 * ## なぜ刻みが要るか
 *
 * 2枚組みだけでは幾何学模様にしか見えない。**刻みがあって初めて「測る道具」だと読める。**
 *
 * ## 長手と妻手
 *
 * **さしがねは L 字の両腕の長さが違う。** 長い方を長手、短い方を妻手という。
 * 等しくすると、それは直角定規であってさしがねではない。
 *
 * 長手 96 : 妻手 48 の **2:1**。実物（1尺5寸 × 7寸5分）の比とほぼ同じで、
 * どちらも `spacing` の段である。
 *
 * ## 寸法は凍結してある
 *
 * 下の数はすべて `spacing` の段から取った。**しかしスケールから導いてはいない。**
 *
 * 導くと、**スケールを触ったときにロゴが黙って変わる。** ロゴはブランドの選択であって
 * システムの選択ではない——原則2 が書体名について言っているのと同じ立場である。
 * 由来を書き残したうえで、値としては固定する。
 *
 * ```
 * spacing = 0, 4, 8, 12, 16, 24, 32, 48, 64, 96   ← 2026-09-05 時点
 * ```
 *
 * | | 値 | 由来 |
 * |---|---|---|
 * | 長手 | 96 | スケールの最大値 |
 * | 妻手 | 48 | 長手のちょうど半分。スケールは2段ごとに倍なので、これも段 |
 * | 板の厚み | 16 | **root。** この系で唯一の根本定数 |
 * | 縁からの余白 | 16 | 厚みと同じにして、板と余白の比を 1:1 にする |
 * | 2枚の隙間 | 32 | 厚みの2倍 |
 * | 長手の刻み | 24・32・48・64 | 厚みより外、長手の先より内側の段すべて |
 * | 妻手の刻み | 24・32 | 同じ規則を妻手の長さに当てたもの |
 * | 長い刻み / 短い刻み | 8 / 4 | 長いのは root の倍加（32・64）に打つ |
 *
 * **隙間は最初 4 にしていた。** 一辺の 3% しかなく、40px まで縮めると隙間が消えて
 * 「点線の四角」に見えた——2枚組みにした理由がそこで失われる。
 * **実際に縮めて見るまで気づかなかった。**
 *
 * **両腕を同じ長さにしていた時期がある**（どちらも 96）。
 * それは直角定規であってさしがねではない。**利用者の指摘で気づいた。**
 *
 * ## 色は誰が持つか
 *
 * | | 色 | なぜ |
 * |---|---|---|
 * | React の部品（`components/mark.tsx`） | **持たない**（`currentColor`） | 置いた場所が決める。明暗の切り替えに追随する |
 * | `public/*.svg` | **持つ**（16進 + `prefers-color-scheme`） | 単体で読まれるので継承する相手がいない |
 * | OG・apple icon | **持つ**（[brand.ts](./brand.ts)） | 1枚の絵に焼かれるので CSS が届かない |
 *
 * SVG ファイルを `currentColor` にしていた時期があるが、
 * **GitHub は `<img>` で描くので黒く潰れた。**
 */

/**
 * 図の一辺。2枚が占めるのは 96 × 96 で、四方に余白 16。
 *
 * **選んだ数ではなく、置いた結果である。**
 */
