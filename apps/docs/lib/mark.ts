  'M38 20h4v4h-4z' + // 24
  'M46 20h4v8h-4z' + // 32
  'M62 20h4v4h-4z' + // 48
  'M78 20h4v8h-4z' + // 64
  // 妻手の刻み
  'M20 38h4v4h-4z' + // 24
  'M20 46h8v4h-8z'; // 32

